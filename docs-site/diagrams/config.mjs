/** The first line of every rendered SVG: which source and config made it. */
export function stampFor(name, source, theme) {
  const hash = createHash('sha256')
    .update(source)
    .update(JSON.stringify(THEMES[theme]))
    .digest('hex');
  return `<!-- Generated by pnpm docs:diagrams from diagrams/${name}.mmd (${theme}, sha256 ${hash}). Do not edit. -->`;
}
