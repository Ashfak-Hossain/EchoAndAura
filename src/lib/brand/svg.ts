import { BRAND_COLORS, LOCKUP, MARK, MARK_SMALL, WORDMARK, type Mark } from './marks';

/** A mark's shapes as SVG markup, in one ink with the given dot colour. */
export function markShapes(mark: Mark, ink: string, dot: string): string {
  const stroke = (s: { d: string; width: number }) =>
    `<path d="${s.d}" fill="none" stroke="${ink}" stroke-width="${s.width}" stroke-linecap="round" stroke-linejoin="round"/>`;
  return (
    stroke(mark.curl) +
    (mark.arc ? stroke(mark.arc) : '') +
    `<circle cx="${mark.dot.cx}" cy="${mark.dot.cy}" r="${mark.dot.r}" fill="${dot}"/>`
  );
}

/**
 * The favicon tile (docs/BRAND.md): the small cut, all marigold, on a rounded
 * charcoal square. `pnpm brand:assets` renders it into favicon.ico and copies
 * it to the docs site as its icon.
 */
export function faviconSvg(): string {
  return (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">' +
    `<rect width="100" height="100" rx="22" fill="${BRAND_COLORS.ink}"/>` +
    `<g transform="translate(15 17) scale(0.7)">${markShapes(MARK_SMALL, BRAND_COLORS.marigold, BRAND_COLORS.marigold)}</g>` +
    '</svg>'
  );
}

/**
 * The lockup as a standalone SVG: charcoal ink, marigold dot and ampersand,
 * on `background` when given (the emailed PNG sits on the white email card).
 * `ink` swaps the charcoal for a dark background (the README's dark logo).
 */
export function lockupSvg({
  width,
  height,
  background,
  ink = BRAND_COLORS.ink,
}: {
  width: number;
  height: number;
  background?: string;
  ink?: string;
}): string {
  const [x, y, w, h] = LOCKUP.viewBox.split(' ');
  const { marigold } = BRAND_COLORS;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="${LOCKUP.viewBox}" preserveAspectRatio="xMidYMid meet">` +
    (background
      ? `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${background}"/>`
      : '') +
    `<g transform="${LOCKUP.markTransform}">${markShapes(MARK, ink, marigold)}</g>` +
    `<g transform="${LOCKUP.wordmarkTransform}">` +
    WORDMARK.parts
      .map((part) => `<path d="${part.d}" fill="${part.role === 'accent' ? marigold : ink}"/>`)
      .join('') +
    '</g></svg>'
  );
}

/**
 * The README's logo: the lockup with no background, in charcoal for GitHub's
 * light theme and in paper for its dark theme (a `<picture>` picks one).
 */
export const README_LOGOS = {
  light: { path: '.github/assets/logo-light.svg', ink: BRAND_COLORS.ink },
  dark: { path: '.github/assets/logo-dark.svg', ink: BRAND_COLORS.paper },
} as const;

export function readmeLogoSvg(theme: keyof typeof README_LOGOS): string {
  const [, , w, h] = LOCKUP.viewBox.split(' ').map(Number) as [number, number, number, number];
  const height = 64;
  return lockupSvg({ width: Math.round((height * w) / h), height, ink: README_LOGOS[theme].ink });
}

/**
 * The docs site is its own package and cannot import from `src/`, so
 * `pnpm brand:assets` writes it a copy of the brand data. A unit test fails
 * when the copy drifts from this source.
 */
export function docsBrandModule(): string {
  const data = { BRAND_COLORS, MARK, LOCKUP, WORDMARK };
  return (
    '// Generated by `pnpm brand:assets` from src/lib/brand/marks.ts. Do not edit.\n' +
    Object.entries(data)
      .map(
        ([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`,
      )
      .join('\n')
  );
}
